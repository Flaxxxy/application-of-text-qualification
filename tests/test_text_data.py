"""Tests for label mapping and text cleaning (CLAUDE.md section 8)."""

import pandas as pd
import pytest

from src.data_text import _fair_quota, balance, clean, combine_title_body, rating_to_label
from src.preprocess_text import basic_clean, clean_for_classical, normalise_for_dedup


# ------------------------------------------------------------- label mapping --

@pytest.mark.parametrize("rating, label", [
    (1, "negative"), (2, "negative"), (3, "neutral"), (4, "positive"), (5, "positive"),
    (5.0, "positive"), ("4", "positive"),
])
def test_rating_to_label(rating, label):
    assert rating_to_label(rating) == label


@pytest.mark.parametrize("rating", [0, 6, 3.5, None, "Bajaj DX 2 L/W Dry Iron", float("nan")])
def test_invalid_ratings_get_no_label(rating):
    assert rating_to_label(rating) is None


# ------------------------------------------------------------ title + body --

def test_title_and_body_are_joined():
    assert combine_title_body("Does not work", "Tried twice.") == "Does not work. Tried twice."
    assert combine_title_body("Great!", "Love it") == "Great! Love it"


def test_automatic_star_title_is_dropped():
    # "Five Stars" is generated by Amazon from the rating and would leak the label.
    assert combine_title_body("Five Stars", "Works fine") == "Works fine"
    assert combine_title_body("1 star", "Broke in a day") == "Broke in a day"


def test_title_repeated_in_body_is_not_doubled():
    assert combine_title_body("Good", "Good product, fast delivery") == "Good product, fast delivery"


# ---------------------------------------------------------------- cleaning --

def test_basic_clean_removes_html_and_urls():
    text = "Great&amp;cheap<br /><br />see https://example.com/x   now"
    assert basic_clean(text) == "Great&cheap see now"


def test_classical_clean_keeps_negations():
    # Removing "not" would flip the meaning, so it must survive stopword removal.
    out = clean_for_classical("The boxes were NOT damaged!!")
    assert out == "box not damaged"
    assert "not" in clean_for_classical("It isn't working").split()
    assert "never" in clean_for_classical("I will never buy this again").split()


def test_classical_clean_removes_stopwords_and_punctuation():
    out = clean_for_classical("This is the best product, and I love it!")
    assert "the" not in out.split() and "," not in out
    assert "best" in out and "love" in out


def test_dedup_normalisation():
    assert normalise_for_dedup("Great product!!") == normalise_for_dedup("great   PRODUCT")


# ------------------------------------------------------------ clean + balance --

def _df(rows):
    return pd.DataFrame(rows, columns=["review_id", "source", "category", "text", "rating", "label"])


def test_clean_drops_short_duplicates_and_conflicts():
    df = _df([
        ["1", "a", "x", "really great value here", 5, "positive"],
        ["2", "a", "x", "Really great value here!", 5, "positive"],   # duplicate
        ["3", "a", "x", "ok", 3, "neutral"],                          # too short
        ["4", "a", "x", "it is fine i guess", 3, "neutral"],
        ["5", "b", "x", "it is fine I guess", 5, "positive"],         # same text, other label
        ["6", "a", "x", "no label for this one", None, None],
    ])
    out = clean(df)
    assert out["review_id"].tolist() == ["1"]


def test_fair_quota_gives_leftover_to_bigger_sources():
    assert _fair_quota({"small": 10, "big1": 100, "big2": 100}, 90) == {"small": 10, "big1": 40, "big2": 40}


def test_balance_caps_class_ratio_inside_a_source():
    rows = [[f"a{i}", "a", "x", "t", 5, "positive"] for i in range(50)]
    rows += [[f"a_n{i}", "a", "x", "t", 1, "negative"] for i in range(5)]
    out = balance(_df(rows), per_class=100, seed=42, max_class_ratio=3)
    counts = out["label"].value_counts()
    assert counts["positive"] == 15 and counts["negative"] == 5
